export type Topic = {
  emoji: string
  theme: string
  question: string
  followUp: string
}

export function generateTopics(profile: SelfProfile): Topic[] {
  const topics: Topic[] = []

  if (profile.hobbies.includes('音楽') || profile.entertainment.some(e => ['邦楽','洋楽','K-POP','ライブ・フェス'].includes(e))) {
    topics.push({ emoji: '🎵', theme: '音楽', question: '最近よく聴いてるアーティストや曲はありますか？', followUp: 'ライブやフェスには行きますか？おすすめがあれば教えて！' })
  }
  if (profile.hobbies.includes('映画・ドラマ') || profile.entertainment.some(e => ['映画館','Netflix・Disney+'].includes(e))) {
    topics.push({ emoji: '🎬', theme: '映画・ドラマ', question: '最近見た映画やドラマで面白かったものはありますか？', followUp: '映画館派？配信派？ジャンルの好みも聞かせて！' })
  }
  if (profile.hobbies.includes('アニメ・漫画')) {
    topics.push({ emoji: '✨', theme: 'アニメ・漫画', question: '好きなアニメや漫画の作品はありますか？', followUp: '最近追いかけてる作品や、ずっと好きな名作など教えて！' })
  }
  if (profile.hobbies.includes('ゲーム') || profile.entertainment.includes('ゲーム実況')) {
    topics.push({ emoji: '🎮', theme: 'ゲーム', question: '最近ハマっているゲームや昔好きだったゲームはありますか？', followUp: 'ソシャゲ・コンシューマー・PCどれが多いですか？' })
  }
  if (profile.hobbies.includes('スポーツ') || profile.entertainment.includes('スポーツ観戦')) {
    topics.push({ emoji: '⚽', theme: 'スポーツ', question: 'スポーツは何かやっていますか？観戦は好きですか？', followUp: 'チームのファンだったりしますか？推しチームや選手がいれば教えて！' })
  }
  if (profile.hobbies.includes('読書')) {
    topics.push({ emoji: '📚', theme: '読書', question: '最近読んだ本でおすすめはありますか？', followUp: '小説・ビジネス書・漫画？ジャンルや好きな作家さんも聞かせて！' })
  }
  if (profile.hobbies.includes('料理')) {
    topics.push({ emoji: '🍳', theme: '料理', question: '料理はよく作りますか？得意な料理はありますか？', followUp: 'お気に入りのレシピや食材こだわりも聞かせて！' })
  }
  if (profile.travel.length > 0) {
    topics.push({ emoji: '✈️', theme: '旅行', question: '最近行った場所や行きたい場所はありますか？', followUp: profile.travel.includes('海外旅行') ? '海外で印象に残った国や都市はどこですか？' : '国内でおすすめのスポットはありますか？' })
  }
  if (profile.hobbies.includes('ファッション')) {
    topics.push({ emoji: '👗', theme: 'ファッション', question: '最近お気に入りのブランドやファッションのテイストはありますか？', followUp: 'ショッピングはどこでしますか？オンライン派？お店派？' })
  }
  if (profile.foods.likes.length > 0) {
    topics.push({ emoji: '🍽️', theme: 'グルメ', question: `${profile.foods.likes[0]}が好きとのことですが、おすすめのお店や食べ方はありますか？`, followUp: '最近行ったおいしいお店があれば教えてください！' })
  }
  if (profile.mbti) {
    topics.push({ emoji: '🧠', theme: 'MBTI・性格', question: `MBTIは${profile.mbti}なんですね！相手の方もMBTI知っているか聞いてみては？`, followUp: '性格診断って当たってると思いますか？' })
  }
  if (profile.personality.includes('外向的') || profile.personality.includes('好奇心旺盛')) {
    topics.push({ emoji: '🌟', theme: '挑戦・目標', question: '最近チャレンジしたことや、これからやってみたいことはありますか？', followUp: '新しいことを始めるとき、どんなきっかけが多いですか？' })
  }

  topics.push({ emoji: '💭', theme: 'もしも話', question: '明日から1週間自由に使えるとしたら、何をしたいですか？', followUp: '理想の休日の過ごし方はどんな感じですか？' })
  topics.push({ emoji: '🏆', theme: '得意なこと', question: '自分が得意だと思うことや、よく人に頼まれることはありますか？', followUp: 'それはどうやって身につけたのですか？' })

  return topics
}
